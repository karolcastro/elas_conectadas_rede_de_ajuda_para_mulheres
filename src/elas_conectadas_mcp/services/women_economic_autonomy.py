class WomenEconomicAutonomyDirectory:
    """Busca iniciativas e oportunidades com status, público e modalidade transparentes."""

    def search(
        self,
        *,
        uf: str | None = None,
        publico: str | None = None,
        tipo: str | None = None,
        incluir_encerradas: bool = True,
    ) -> dict[str, Any]:
        normalized_uf = uf.strip().upper() if uf else None
        if normalized_uf and (len(normalized_uf) != 2 or not normalized_uf.isalpha()):
            raise ValueError("Informe uma sigla de UF válida com duas letras.")

        allowed_groups = {
            "negras", "indigenas", "quilombolas", "coletivos",
            "empreendedoras", "vulnerabilidade_social",
        }
        if publico and publico not in allowed_groups:
            raise ValueError("Público inválido. Consulte os filtros disponíveis.")

        allowed_types = {
            "financiamento", "capacitacao", "fortalecimento_coletivo", "articulacao",
        }
        if tipo and tipo not in allowed_types:
            raise ValueError("Tipo de oportunidade inválido. Consulte os filtros disponíveis.")

        results = []
        for item in OPPORTUNITIES:
            if normalized_uf and item["coverage"] != "Brasil" and normalized_uf not in item["ufs"]:
                continue
            if publico and publico not in item["audience_groups"]:
                continue
            if tipo and tipo not in item["opportunity_types"]:
                continue
            if not incluir_encerradas and item["status"] in {
                "inscricoes_encerradas", "edicao_encerrada",
            }:
                continue
            results.append(item)

        status_order = {
            "inscricoes_abertas": 0,
            "apoio_aberto_apenas_coorte": 1,
            "monitorar_nova_edicao": 2,
            "programa_permanente_sem_chamada_confirmada": 3,
            "programa_em_execucao_sem_inscricao_publica": 4,
            "rede_e_referencia_sem_edital_financeiro_confirmado": 5,
            "inscricoes_encerradas": 6,
            "edicao_encerrada": 7,
        }
        results.sort(key=lambda item: (status_order.get(item["status"], 99), item["name"].casefold()))
        return {
            "opportunities": results,
            "count": len(results),
            "filters": {
                "uf": normalized_uf,
                "publico": publico,
                "tipo": tipo,
                "incluir_encerradas": incluir_encerradas,
            },
            "status_legend": {
                "inscricoes_abertas": "Página oficial informa inscrições abertas; confirme se o formulário ainda recebe candidaturas.",
                "apoio_aberto_apenas_coorte": "Somente participantes já selecionadas de uma turma podem concorrer ao apoio financeiro.",
                "monitorar_nova_edicao": "Nova edição anunciada como futura, sem prazo de inscrição publicado.",
                "programa_permanente_sem_chamada_confirmada": "Programa institucional existente, mas sem chamada pública aberta confirmada.",
                "programa_em_execucao_sem_inscricao_publica": "Projeto em execução com organizações selecionadas; não há inscrição pública confirmada.",
                "rede_e_referencia_sem_edital_financeiro_confirmado": "Rede de articulação e informação; não é edital de financiamento.",
                "inscricoes_encerradas": "Prazo da chamada encerrado; acompanhar nova edição.",
                "edicao_encerrada": "Edição anterior concluída; acompanhar nova edição.",
            },
            "important_notice": (
                "Oportunidades são classificadas conforme fonte oficial e data de verificação. "
                "Não confunda empréstimo/crédito com bolsa, doação ou capital não reembolsável. "
                "Quando o edital não esclarece a natureza do repasse, o agente deve dizer que "
                "é necessário consultar o regulamento. Inscrições abertas podem se encerrar ou "
                "mudar; confirme diretamente com a organização. O agente não exige cadastro, "
                "login, CPF, e-mail, senha ou relato pessoal para apresentar estas informações."
            ),
            "verification_date": "2026-11-04",
        }
